import assert from "node:assert/strict";
import { execFileSync, spawnSync } from "node:child_process";
import { cpSync, mkdtempSync, mkdirSync, rmSync, writeFileSync } from "node:fs";
import os from "node:os";
import path from "node:path";
import test from "node:test";
import { fileURLToPath } from "node:url";
import { validateCommitHistory, validateCommitMessage } from "./check-commit-message.mjs";
import { validateOutgoingObjects } from "./run-git-hook.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");

test("allows human attribution and ordinary Claude integration changes", () => {
  assert.doesNotThrow(() => validateCommitMessage(
    "Fix Claude transcript parsing\n\nCo-Authored-By: Jane Doe <jane@example.com>\nSigned-off-by: Memo Garcia <memo@example.com>\n"
  ));
});

for (const message of [
  "Fix bug\n\nCo-Authored-By: Claude Opus 5.5 <noreply@anthropic.com>",
  "Fix bug\r\n\r\nco-authored-by: Assistant <noreply@anthropic.com>\r\n",
  "Fix bug\n\nAssisted-by: Anthropic",
  "Fix bug\n\n🤖 Generated with [Claude Code](https://claude.com/claude-code)",
  "Fix bug\n\nGenerated by Claude",
  "Fix bug\n\nClaude-Session: session-id",
  "Fix bug\n\nhttps://claude.ai/code/session-id"
]) {
  test(`rejects forbidden attribution: ${message.split("\n").at(-1)}`, () => {
    assert.throws(() => validateCommitMessage(message), /attribution is forbidden/);
  });
}

test("installed hooks reject commits and outgoing history with forbidden attribution", () => {
  const cwd = mkdtempSync(path.join(os.tmpdir(), "antibody-attribution-test-"));
  const env = {
    ...process.env,
    GIT_CONFIG_GLOBAL: os.devNull,
    GIT_CONFIG_NOSYSTEM: "1",
    GIT_AUTHOR_NAME: "Test Human",
    GIT_AUTHOR_EMAIL: "human@example.com",
    GIT_COMMITTER_NAME: "Test Human",
    GIT_COMMITTER_EMAIL: "human@example.com"
  };
  const git = (args) => execFileSync("git", args, { cwd, env, encoding: "utf8", stdio: "pipe" });
  try {
    git(["init", "--quiet"]);
    // Simulate an old commit created before the repository hooks existed.
    git(["commit", "--allow-empty", "-m", "Old commit\n\nCo-Authored-By: Claude <noreply@anthropic.com>"]);
    mkdirSync(path.join(cwd, "scripts"));
    cpSync(path.join(root, ".husky"), path.join(cwd, ".husky"), { recursive: true });
    cpSync(path.join(root, "scripts/git-hooks"), path.join(cwd, "scripts/git-hooks"), { recursive: true });
    execFileSync("sh", [path.join(root, "scripts/install-git-hooks.sh")], { cwd, env, stdio: "pipe" });
    assert.equal(git(["config", "core.hooksPath"]).trim(), ".husky");

    const messageFile = path.join(cwd, "message.txt");
    writeFileSync(messageFile, "New commit\n\nCo-Authored-By: Claude <noreply@anthropic.com>\n");
    const before = git(["rev-parse", "HEAD"]).trim();
    const rejected = spawnSync("git", ["commit", "--allow-empty", "-F", messageFile], { cwd, env, encoding: "utf8" });
    assert.notEqual(rejected.status, 0);
    assert.match(rejected.stderr, /attribution is forbidden/);
    assert.equal(git(["rev-parse", "HEAD"]).trim(), before);

    git(["commit", "--allow-empty", "-m", "Human change", "--signoff"]);
    const tip = git(["rev-parse", "HEAD"]).trim();
    assert.doesNotThrow(() => validateCommitHistory([tip, "--no-walk"], cwd));
    assert.throws(() => validateCommitHistory(["HEAD"], cwd), /attribution is forbidden/);
    assert.throws(() => validateOutgoingObjects({
      cwd,
      remoteName: "origin",
      input: `refs/heads/main ${tip} refs/heads/main ${"0".repeat(40)}\n`
    }), /attribution is forbidden/);
  } finally {
    rmSync(cwd, { recursive: true, force: true });
  }
});
